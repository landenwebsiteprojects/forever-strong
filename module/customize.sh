#!/system/bin/sh
SKIPUNZIP=0
ui_print 'Initializing ForeverStrong v1.0'
[ "$BOOTMODE" = true ] || abort 'Install through Magisk/Kitsune, KernelSU or APatch Manager while Android is running.'
ui_print 'Checking device environment'
[ "$API" -ge 29 ] || abort 'Android 10 (API 29) or later is required.'
case "$ARCH" in
    arm64) HE_ABI=arm64-v8a;; arm) HE_ABI=armeabi-v7a;; x64) HE_ABI=x86_64;; x86) HE_ABI=x86;;
    *) abort "Unsupported architecture: $ARCH";;
esac
STATE=/data/adb/halloweenedition
OLD=/data/adb/modules/halloweenedition
BOX=/data/adb/Box-Brain
TS=/data/adb/tricky_store
# No mutation until archive and conflict checks pass.
ui_print 'Verifying package contents'
HE_VERIFY_LOG="${TMPDIR:-$MODPATH}/halloween-verify.log"
if ! (cd "$MODPATH" && sha256sum -c files.sha256) > "$HE_VERIFY_LOG" 2>&1; then
    while IFS= read -r line; do
        case "$line" in *': OK') ;; *) ui_print "$line";; esac
    done < "$HE_VERIFY_LOG"
    abort 'Package checksum verification failed. The missing or damaged file is listed above.'
fi
rm -f "$HE_VERIFY_LOG"
HE_INSTALLING=true
. "$MODPATH/bin/root-compat.sh"
he_setup_runtime
[ "$HE_ROOT_MANAGER" != unknown ] || abort 'Unsupported root manager. Use Magisk/Kitsune, KernelSU or APatch Manager.'
command -v resetprop >/dev/null 2>&1 || abort 'The active root manager does not provide resetprop. Repair its module environment before installing.'
ui_print "Root manager: $(he_root_label)"
HE_INSTALLING=false
for id in playintegrityfix playintegrity tricky_store teesim oh_my_keymint; do
    for root in /data/adb/modules /data/adb/modules_update; do
        p="$root/$id"
        if [ -d "$p" ] && [ ! -f "$p/disable" ] && [ ! -f "$p/remove" ]; then
            abort "Conflict: $id is enabled or queued. Disable it in Manager, reboot, then install. No files were deleted."
        fi
    done
done
# Refuse unidentified global hook scripts; their generic filenames do not prove ownership.
while read -r expected name; do
    p="/data/adb/service.d/$name"
    [ -e "$p" ] || continue
    actual=$(sha256sum "$p" | cut -d' ' -f1)
    [ "$actual" = "$expected" ] || abort "Unrecognized service.d/$name. Back it up and resolve it before installation."
done < "$MODPATH/bin/legacy-hooks.sha256"
umask 077
mkdir -p "$STATE" "$TS" "$BOX/PIF" || abort 'Cannot prepare configuration storage.'
SNAP="$STATE/migration/$(date +%Y%m%d-%H%M%S)-$$"
mkdir -p "$SNAP/hooks" || abort 'Cannot prepare migration backup.'
# Capture user configs before any defaults. Do not copy keys to shared storage.
for path in "$BOX" "$TS"; do
    [ ! -d "$path" ] || cp -a "$path" "$SNAP/" || abort 'Configuration backup failed.'
done
ui_print 'Preparing core components'
# Preserve module-local settings from previous Halloween release or the disabled baseline.
SOURCE="$OLD"
[ -f "$SOURCE/module.prop" ] || SOURCE=/data/adb/modules/playintegrityfix
if [ -d "$SOURCE" ]; then
    for f in custom.pif.prop custom.pif.json pif.prop pif.json apps.txt app_profile.prop stop skippersistprop skipdelprop; do
        if [ -f "$SOURCE/$f" ] && [ ! -L "$SOURCE/$f" ]; then cp -p "$SOURCE/$f" "$MODPATH/$f" || abort "Cannot retain $f"; fi
    done
    [ ! -d "$SOURCE/system" ] || cp -a "$SOURCE/system" "$MODPATH/" || abort 'Cannot preserve app replacement settings.'
fi
# Preserve restore commands generated by the upstream persistent-property helper.
if [ -f "$SOURCE/uninstall.sh" ]; then
    grep '^resetprop ' "$SOURCE/uninstall.sh" >> "$MODPATH/uninstall.sh" || true
fi
[ -f "$MODPATH/custom.pif.prop" ] || {
    if [ "$API" -ge 33 ]; then cp "$MODPATH/toolkit/pixelify.prop" "$MODPATH/custom.pif.prop"; else cp "$MODPATH/toolkit/legacy.prop" "$MODPATH/custom.pif.prop"; fi
}
if [ ! -f "$TS/keybox.xml" ]; then cp "$MODPATH/tricky/keybox.xml" "$TS/keybox.xml" || abort 'Cannot install default AOSP keybox.'; fi
if [ ! -f "$TS/target.txt" ]; then cp "$MODPATH/tricky/target.txt" "$TS/target.txt" || abort 'Cannot install target defaults.'; fi
# An absent patch file is meaningful to OSS. Do not create or overwrite it on migration.
if [ ! -e "$BOX/pixelify" ] && [ ! -e "$BOX/legacy" ] && [ ! -e "$BOX/advanced" ] && [ ! -e "$BOX/wipe" ]; then
    if [ "$API" -ge 33 ]; then touch "$BOX/pixelify"; else touch "$BOX/legacy"; fi
    touch "$BOX/safemode" "$BOX/noredirect" "$BOX/PIF/skip_json" "$BOX/PIF/skip_key"
fi
[ -e "$BOX/hash.txt" ] || touch "$BOX/hash.txt"
ui_print 'Integrating module services'
cp "$MODPATH/tricky/lib/$HE_ABI/libinject.so" "$MODPATH/tricky/inject" || abort 'Missing OSS injector.'
cp "$MODPATH/tricky/lib/$HE_ABI/libTrickyStoreOSS.so" "$MODPATH/tricky/libTrickyStoreOSS.so" || abort 'Missing OSS library.'
# Integrity Box's ShadowHook payload supports ARM; x86 uses its supplied Dobby fallback.
case "$HE_ABI" in
    x86|x86_64)
        cp "$MODPATH/legacy/zygisk/$HE_ABI.so" "$MODPATH/zygisk/$HE_ABI.so" || abort 'Missing legacy native payload.'
        cp "$MODPATH/legacy/legacy.dex" "$MODPATH/classes.dex" || abort 'Missing legacy DEX.';;
esac
if [ -e /sdcard/zygisk ] || [ -f "$BOX/zygisk" ]; then
    # Preserve user-requested scripts-only behavior while OSS remains active.
    rm -rf "$MODPATH/zygisk"
    touch "$BOX/zygisk"
fi
ui_print 'Configuring WebUI'
set_perm_recursive "$MODPATH" 0 0 0755 0644
find "$MODPATH" -name '*.sh' -exec chmod 0755 {} \;
chmod 0755 "$MODPATH/tricky/daemon" "$MODPATH/tricky/inject"
chmod 0700 "$STATE"
chmod 0600 "$TS/keybox.xml" "$TS/target.txt"
# Only exact known upstream scripts are quarantined. Their bytes are preserved for rollback.
while read -r expected name; do
    p="/data/adb/service.d/$name"
    [ ! -e "$p" ] || mv "$p" "$SNAP/hooks/$name" || abort 'Cannot quarantine legacy startup hook.'
done < "$MODPATH/bin/legacy-hooks.sha256"
printf '%s\n' "$HE_ROOT_MANAGER" > "$STATE/root-manager"
ui_print 'Zygisk features need an active Zygisk loader; KernelSU/APatch need a compatible external loader.'
ui_print 'Scripts-only mode and the bundled OSS daemon do not require Zygisk.'
ui_print 'Verifying installation'
for f in module.prop classes.dex tricky/classes.dex tricky/inject tricky/libTrickyStoreOSS.so bin/validator.dex bin/integration.sh bin/engine-control.sh bin/tricky-supervisor.sh webroot/index.html webroot/integration.js webroot/RepairMode/repair.js; do
    [ -s "$MODPATH/$f" ] || abort "Required component missing: $f"
done
printf '%s\n' "$SNAP" > "$STATE/last-migration"
ui_print 'Installation completed'
ui_print 'Reboot, then open ForeverStrong with a root WebUI host.'
ui_print 'Previous modules and shared user configurations have been retained.'
